internal enum class DailyMoment(val label:String,val query:String,val description:String){
    FAVORITES("Meu ritmo","","Faixas dos artistas que inspiram seu dia."),
    FOCUS("Concentração","instrumental relaxante","Buscas para um momento de foco e tranquilidade."),
    ENERGY("Energia","músicas animadas","Buscas para momentos de movimento e energia."),
    CAFE("Midnight Café","músicas românticas","Buscas inspiradas em romance e noites intimistas.")
}
internal fun dailyPremiumSeeds(artists:List<String>,day:Long):List<String>{
    val list=artists.map{NeroFollowedArtists.clean(it)}.filter{it.length>=3}.distinctBy(::nativeArtistKey).take(12)
    if(list.isEmpty())return emptyList()
    val offset=Math.floorMod(day,list.size.toLong()).toInt()
    return (list.drop(offset)+list.take(offset)).take(3)
}
internal fun dailyMomentQuery(artist:String,moment:DailyMoment):String =
    listOf(NeroFollowedArtists.clean(artist).take(70),moment.query).filter{it.isNotBlank()}.joinToString(" ").take(100)

internal fun premiumDailyCollections(groups:List<Pair<String,List<NativeMusicHit>>>,day:Long,excluded:Set<String>,hidden:Set<String>):List<NeroDailyCollection>{
    val used=mutableSetOf<String>()
    return groups.distinctBy{nativeArtistKey(it.first)}.take(3).mapNotNull{(artist,rows)->
        val candidates=rows.filter{recommendationId(it.id)==it.id&&it.id !in excluded&&it.id !in hidden&&it.title.isNotBlank()}.distinctBy{it.id}
        if(candidates.isEmpty())return@mapNotNull null
        val offset=Math.floorMod(day+nativeArtistKey(artist).hashCode().toLong(),candidates.size.toLong()).toInt()
        val selected=(candidates.drop(offset)+candidates.take(offset)).filter{it.id !in used}.take(15)
        used.addAll(selected.map{it.id})
        if(selected.isEmpty())null else NeroDailyCollection(artist,selected)
    }
}

@Composable
internal fun NeroDailyMixPremium(uid:String,artists:List<String>,day:Long,excluded:Set<String>,hidden:Set<String>,canPlay:Boolean,onQueue:(List<MediaItem>,Int)->Unit){
    val context=LocalContext.current
    key(uid,artists,day){
        val scope=rememberCoroutineScope()
        val seeds=remember(artists,day){dailyPremiumSeeds(artists,day)}
        var moment by remember{mutableStateOf(DailyMoment.FAVORITES)}
        var verified by remember{mutableStateOf(false)}
        var checked by remember{mutableStateOf(false)}
        var busy by remember{mutableStateOf(false)}
        var notice by remember{mutableStateOf<String?>(null)}
        var generated by remember{mutableStateOf(emptySet<DailyMoment>())}
        var results by remember{mutableStateOf(emptyMap<DailyMoment,List<Pair<String,List<NativeMusicHit>>>>())}
        fun active()=NeroSupabase.identityReady.value&&NeroSupabase.activeUid.value==uid&&NeroReplay.today()==day
        fun revoke(){verified=false;checked=true;results=emptyMap();generated=emptySet()}
        LaunchedEffect(verified){
            if(verified){delay(300000L);revoke()}
        }
        val collections=remember(results,moment,day,excluded,hidden,verified){
            if(verified)premiumDailyCollections(results[moment].orEmpty(),day,excluded,hidden)else emptyList()
        }
        Text("NERO Daily Mix Premium",fontSize=21.sp,fontWeight=FontWeight.Bold,color=Color(0xFF39FF14))
        Text("Coleções do dia inspiradas nos seus artistas e no momento que você escolher.",fontSize=12.sp,color=Color.LightGray)
        if(!verified){
            OutlinedButton(enabled=!busy,onClick={
                busy=true;scope.launch{
                    try{verified=verifiedPremium(context,uid)&&active();checked=true}
                    finally{busy=false}
                }
            },modifier=Modifier.fillMaxWidth()){Text(if(busy)"Verificando…" else "Consultar Premium")}
            if(checked&&!verified)Text("Assinatura ativa não confirmada ou sessão expirada.",fontSize=12.sp,color=Color.LightGray)
        }else{
            LazyRow(horizontalArrangement=Arrangement.spacedBy(6.dp)){
                items(DailyMoment.entries){item->FilterChip(selected=moment==item,enabled=!busy,onClick={moment=item;notice=null},label={Text(item.label)})}
            }
            Text(moment.description,fontSize=12.sp,color=if(moment==DailyMoment.CAFE)Color(0xFFE8BB87)else Color.LightGray)
            Text("Artistas do dia: "+seeds.joinToString(" · "),fontSize=12.sp,color=Color.LightGray)
            Text("Ao gerar, os nomes dos artistas e o tema escolhido são enviados à busca musical. O tema é uma sugestão de pesquisa, não uma classificação verificada das faixas.",fontSize=11.sp,color=Color.LightGray)
            OutlinedButton(enabled=!busy&&seeds.isNotEmpty(),onClick={
                val requested=moment
                busy=true;notice=null
                scope.launch{
                    try{
                        if(!verifiedPremium(context,uid)||!active()){revoke();return@launch}
                        val found=mutableListOf<Pair<String,List<NativeMusicHit>>>()
                        var failures=0
                        for(artist in seeds){
                            if(!active()||!verified)return@launch
                            try{found.add(artist to NativeMusicCatalog.search(dailyMomentQuery(artist,requested)).take(20))}
                            catch(e:CancellationException){throw e}catch(_:Exception){failures++}
                        }
                        if(!active()||!verified)return@launch
                        if(found.any{it.second.isNotEmpty()}||failures==0)results=results+(requested to found)
                        generated=generated+requested
                        notice=if(failures>0)"Algumas consultas ficaram indisponíveis." else null
                    }catch(e:CancellationException){throw e}catch(_:Exception){notice="Não foi possível gerar as coleções."}
                    finally{busy=false}
                }
            },modifier=Modifier.fillMaxWidth()){Text(if(busy)"Preparando…" else if(moment in generated)"Atualizar coleções" else "Gerar coleções do dia")}
            if(busy)LinearProgressIndicator(Modifier.fillMaxWidth())
            notice?.let{Text(it,fontSize=12.sp,color=Color.LightGray)}
            if(moment in generated&&collections.isEmpty()&&!busy)Text("Nenhuma faixa adicional encontrada. Experimente outro momento.",fontSize=12.sp,color=Color.LightGray)
            collections.forEach{collection->
                val label=moment.label+" • "+collection.artist
                val play:(List<MediaItem>,Int)->Unit={queue,index->
                    if(!busy&&active()){
                        busy=true;scope.launch{
                            try{
                                if(verifiedPremium(context,uid)&&active()&&verified)onQueue(queue.withOrigin(PlaybackOrigin("mix",label,"")),index)
                                else revoke()
                            }finally{busy=false}
                        }
                    }
                }
                Text(label,fontWeight=FontWeight.Medium,color=if(moment==DailyMoment.CAFE)Color(0xFFE9A3B6)else MaterialTheme.colorScheme.primary)
                Text("${collection.tracks.size} faixas sugeridas",fontSize=12.sp,color=Color.LightGray)
                Button(enabled=canPlay&&!busy,onClick={play(collection.tracks.map{it.queueItem()},0)}){Text("Reproduzir coleção")}
                OnlineDiscoveryRow(collection.tracks,canPlay&&!busy,play)
            }
            Text("Seleção diária local durante esta sessão. Nenhuma atualização automática ou download de áudio.",fontSize=11.sp,color=Color.LightGray)
        }
    }
}
