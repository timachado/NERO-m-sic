package br.com.timachado.neromusic

import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.foundation.text.selection.SelectionContainer
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

@Composable
internal fun NeroConnectProofDialog(uid:String,onClose:()->Unit){
    val context=LocalContext.current
    val scope=rememberCoroutineScope()
    val gate=remember{ConnectProofGate()}
    var generated by remember{mutableStateOf("")}
    var incoming by remember{mutableStateOf("")}
    var answer by remember{mutableStateOf("")}
    var received by remember{mutableStateOf("")}
    var notice by remember{mutableStateOf("")}
    var busy by remember{mutableStateOf(false)}
    DisposableEffect(Unit){onDispose{gate.clear()}}
    fun copy(value:String){
        (context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).setPrimaryClip(ClipData.newPlainText("NERO Connect",value))
    }
    fun run(action:suspend ()->Unit){
        if(busy)return
        busy=true
        scope.launch{
            try{action()}catch(e:CancellationException){throw e}catch(_:Exception){notice="Verificação inválida, expirada ou indisponível."}finally{busy=false}
        }
    }
    AlertDialog(onDismissRequest={if(!busy)onClose()},title={Text("Verificar identidade")},text={
        Column(Modifier.heightIn(max=480.dp).verticalScroll(rememberScrollState()),verticalArrangement=Arrangement.spacedBy(8.dp)){
            Text("Confirme a posse da chave em ambos os aparelhos. O desafio vence em 2 minutos e só pode ser verificado uma vez. Não ativa controle remoto.")
            Text("Neste aparelho: gerar desafio")
            OutlinedButton(enabled=!busy,onClick={run{
                generated=withContext(Dispatchers.IO){NeroConnectIdentity(context.applicationContext,uid).issue(gate)}
                received="";notice="Envie o desafio ao aparelho pareado."
            }}){Text("Gerar desafio")}
            if(generated.isNotBlank()){
                TextButton(onClick={copy(generated)}){Text("Copiar desafio")}
                OutlinedTextField(received,{received=it.take(180)},label={Text("Resposta assinada recebida")},enabled=!busy)
                Button(enabled=!busy&&received.isNotBlank(),onClick={val proof=received;run{
                    val ok=withContext(Dispatchers.IO){NeroConnectIdentity(context.applicationContext,uid).verify(gate,proof)}
                    generated="";received=""
                    notice=if(ok)"Identidade do aparelho confirmada nesta verificação." else "Resposta inválida ou expirada. Gere outro desafio."
                }}){Text("Verificar assinatura")}
            }
            HorizontalDivider()
            Text("No aparelho que recebe um desafio:")
            OutlinedTextField(incoming,{incoming=it.take(256);answer=""},label={Text("Desafio recebido")},enabled=!busy)
            OutlinedButton(enabled=!busy&&incoming.isNotBlank(),onClick={val input=incoming;run{
                answer="";answer=withContext(Dispatchers.IO){NeroConnectIdentity(context.applicationContext,uid).prove(input)}
                notice="Envie a resposta ao outro aparelho."
            }}){Text("Assinar desafio")}
            if(answer.isNotBlank())TextButton(onClick={copy(answer)}){Text("Copiar resposta assinada")}
            if(busy)LinearProgressIndicator(Modifier.fillMaxWidth())
            if(notice.isNotBlank())Text(notice)
        }
    },confirmButton={TextButton(enabled=!busy,onClick=onClose){Text("Fechar")}})
}
