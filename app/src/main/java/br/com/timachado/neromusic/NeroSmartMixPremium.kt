internal enum class PremiumMixMode(val label:String,val description:String){
    AFFINITY("Afinidade","Novas faixas dos artistas que você selecionou."),
    DIVERSITY("Variedade","Distribui sugestões entre diferentes artistas retornados na busca."),
    DISCOVERY("Descobertas","Prioriza artistas ainda não encontrados no seu histórico, favoritos ou seguidos.")
}
internal fun premiumMixRows(groups:List<List<NativeMusicHit>>,seeds:List<String>,known:List<String>,mode:PremiumMixMode,excluded:Set<String>,hidden:Set<String>,limit:Int):List<NativeMusicHit>{
    require(limit in setOf(15,30))
    val seedKeys=seeds.map(::nativeArtistKey).toSet()
    val knownKeys=(known+seeds).map(::nativeArtistKey).toSet()
    val all=groups.flatten().filter{row->
        recommendationId(row.id)==row.id&&row.id !in excluded&&row.id !in hidden&&row.title.isNotBlank()&&
            nativeArtistKey(row.artist).let{it.length>=3&&it !in setOf("unknown","unknown artist","artista desconhecido","<unknown>")}
    }.distinctBy{it.id}
    val candidates=when(mode){
        PremiumMixMode.AFFINITY->all.filter{nativeArtistKey(it.artist) in seedKeys}
        PremiumMixMode.DIVERSITY->all
        PremiumMixMode.DISCOVERY->all.filter{nativeArtistKey(it.artist) !in knownKeys}
    }
    val buckets=candidates.groupBy{nativeArtistKey(it.artist)}.values.toList()
    if(buckets.isEmpty())return emptyList()
    return interleaveNeroMix(buckets,excluded,hidden,limit)
}
@Composable
internal fun NeroSmartMixPremium(uid:String,seeds:List<String>,known:List<String>,excluded:Set<String>,hidden:Set<String>,canPlay:Boolean,onQueue:(List<MediaItem>,Int)->Unit){
    val context=LocalContext.current
    key(uid,seeds){
        val scope=rememberCoroutineScope()
        var checked by remember{mutableStateOf(false)}
        var verified by remember{mutableStateOf(false)}
        var busy by remember{mutableStateOf(false)}
        var selected by remember{mutableStateOf(seeds.take(3).toSet())}
        var mode by remember{mutableStateOf(PremiumMixMode.AFFINITY)}
        var limit by remember{mutableIntStateOf(30)}
        var groups by remember{mutableStateOf(emptyList<List<NativeMusicHit>>())}
        var generated by remember{mutableStateOf(false)}
        var notice by remember{mutableStateOf<String?>(null)}
        fun active()=NeroSupabase.identityReady.value&&NeroSupabase.activeUid.value==uid
        fun invalidate(){groups=emptyList();generated=false;notice=null}
        LaunchedEffect(verified){
            if(verified){delay(300000L);verified=false;checked=false;invalidate()}
        }
        val chosen=seeds.filter{it in selected}
        val rows=remember(groups,chosen,known,mode,excluded,hidden,limit,verified){
            if(verified)premiumMixRows(groups,chosen,known,mode,excluded,hidden,limit)else emptyList()
        }
        Text("NERO Smart Mix Premium",fontSize=21.sp,fontWeight=FontWeight.Bold,color=Color(0xFF39FF14))
        Text("Escolha até seis artistas, o estilo das sugestões e a quantidade de faixas. Os mixes básicos continuam gratuitos.",fontSize=12.sp,color=Color.LightGray)
        if(!verified){
            OutlinedButton(enabled=!busy,onClick={
                busy=true;scope.launch{
                    try{verified=verifiedPremium(context,uid)&&active();checked=true}
                    finally{busy=false}
                }
            },modifier=Modifier.fillMaxWidth()){Text(if(busy)"Verificando…" else "Consultar Premium")}
            if(checked&&!verified)Text("Assinatura ativa não confirmada.",fontSize=12.sp,color=Color.LightGray)
        }else{
            Text("Artistas selecionados: ${chosen.size}/6",fontWeight=FontWeight.Medium)
            LazyRow(horizontalArrangement=Arrangement.spacedBy(6.dp)){
                items(seeds,key={nativeArtistKey(it)}){artist->
                    FilterChip(selected=artist in selected,enabled=!busy&&(artist in selected||selected.size<6),onClick={
                        selected=if(artist in selected)selected-artist else selected+artist
                        invalidate()
                    },label={Text(displayArtistName(artist))})
                }
            }
            LazyRow(horizontalArrangement=Arrangement.spacedBy(6.dp)){
                items(PremiumMixMode.entries){option->
                    FilterChip(selected=mode==option,enabled=!busy,onClick={mode=option;notice=null},label={Text(option.label)})
                }
            }
            Text(mode.description,fontSize=12.sp,color=Color.LightGray)
            Row(horizontalArrangement=Arrangement.spacedBy(8.dp)){
                listOf(15,30).forEach{count->FilterChip(selected=limit==count,enabled=!busy,onClick={limit=count},label={Text("$count faixas")})}
            }
            Text("Ao gerar, somente os nomes dos artistas escolhidos são consultados na fonte musical. Resultados dependem da disponibilidade do catálogo.",fontSize=11.sp,color=Color.LightGray)
            OutlinedButton(enabled=!busy&&chosen.isNotEmpty(),onClick={
                busy=true;invalidate()
                scope.launch{
                    try{
                        if(!verifiedPremium(context,uid)||!active()){verified=false;checked=true;return@launch}
                        val found=mutableListOf<List<NativeMusicHit>>()
                        var failures=0
                        for(artist in chosen){
                            if(!active()||!verified)return@launch
                            try{found.add(NativeMusicCatalog.search(artist).take(20))}
                            catch(e:CancellationException){throw e}catch(_:Exception){failures++}
                        }
                        if(!active()||!verified)return@launch
                        groups=found;generated=true
                        notice=if(failures>0)"Algumas consultas ficaram indisponíveis." else null
                    }catch(e:CancellationException){throw e}catch(_:Exception){notice="Não foi possível gerar o mix."}
                    finally{busy=false}
                }
            },modifier=Modifier.fillMaxWidth()){Text(if(busy)"Preparando…" else "Gerar mix personalizado")}
            if(busy)LinearProgressIndicator(Modifier.fillMaxWidth())
            notice?.let{Text(it,fontSize=12.sp,color=Color.LightGray)}
            if(generated&&rows.isEmpty())Text("Nenhuma faixa para este modo. Experimente outro modo ou outros artistas.",fontSize=12.sp,color=Color.LightGray)
            if(rows.isNotEmpty()){
                Text("${rows.size} faixas · "+mode.label,fontSize=13.sp)
                // Each playback action rechecks entitlement. Basic playback stays unchanged.
                val play:(List<MediaItem>,Int)->Unit={queue,index->
                    if(!busy&&active()){
                        busy=true;scope.launch{
                            try{
                                if(verifiedPremium(context,uid)&&active()&&verified)onQueue(queue,index)
                                else{verified=false;checked=true;invalidate()}
                            }finally{busy=false}
                        }
                    }
                }
                Button(enabled=canPlay&&!busy,onClick={play(rows.map{it.queueItem()}.withOrigin(PlaybackOrigin("mix","Smart Mix Premium • "+mode.label,"")),0)}){Text("Reproduzir mix")}
                OnlineDiscoveryRow(rows,canPlay&&!busy,play)
            }
        }
    }
}
